const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const root=path.join(__dirname,'../js/features/');
let now=100000000, sid='one',values={},out=[],ins=[],cards=[],roll=.5;
const ctx={console,Date,Math,setTimeout,clearTimeout,setInterval,clearInterval};ctx.window=ctx;
vm.createContext(ctx);vm.runInContext(fs.readFileSync(root+'ask-core.js','utf8'),ctx);
vm.runInContext(fs.readFileSync(root+'mochi-ask-bank.js','utf8'),ctx);
const A=ctx.AskCore;A.init({partnerId:()=>sid,nowMs:()=>now,rnd:()=>roll,store:{get:k=>values[k],set:(k,v)=>values[k]=v},onAskCard:c=>cards.push(c),onChatOut:t=>out.push(t),onChatIn:t=>ins.push(t),chatStyleReply:()=> '字卡回复'});
A.importBank(ctx.MOCHI_ASK_QUESTIONS);assert.equal(A.questions().length,87);
A.setQuestionEnabled('q_d1',false);assert.equal(A.questions().find(q=>q.id==='q_d1').enabled,false);
A.configure({useDefault:false,prob:100});
A.addQuestion({text:'文本测试',type:'text'});
let c=A.triggerNow().card;assert(c);assert(A.answerCard(c.ts,'回答').ok);assert.equal(A.answerCard(c.ts,'再次').why,'answered');assert.equal(out.length,1);
assert.equal(A.tick().why,'cool');now+=46*60000;assert.equal(A.tick().why,'gate');now+=15*60000;assert(A.tick().fired);
A.markGate();now+=46*60000;assert.equal(A.tick().why,'gate');
A.questions().filter(q=>!q.isPreset).forEach(q=>A.setQuestionEnabled(q.id,false));
A.addQuestion({text:'单选',type:'single',options:[{t:'A',reply:'答A'},{t:'B',reply:'答B'}]});
c=A.triggerNow().card;assert.equal(A.answerCard(c.ts,{option:'X'}).why,'bad-option');assert.equal(A.answerCard(c.ts,{option:'B'}).reply,'答B');
A.questions().filter(q=>!q.isPreset).forEach(q=>A.setQuestionEnabled(q.id,false));
A.addQuestion({text:'多选',type:'multi',multiMax:2,options:[{t:'A',reply:'答A'},{t:'B',reply:'答B'},{t:'C',reply:'答C'}]});
c=A.triggerNow().card;assert.equal(A.answerCard(c.ts,{options:['A','B','C']}).why,'over-cap');
A.configure({useChatReply:true});assert.equal(A.answerCard(c.ts,{options:['A','B']}).reply,'字卡回复');
const sameTime=A.triggerNow().card;assert.notEqual(c.ts,sameTime.ts);
A.setDeadline(now-1);assert.equal(A.answerCard(sameTime.ts,{options:['A']}).why,'deadline');assert.equal(A.triggerNow().why,'deadline');
sid='two';assert.equal(A.history().length,0);sid='one';assert(A.history().length>=4);
assert.equal(A.removeQuestion('q_d2').why,'preset');
assert.equal(out.length,ins.length);
console.log('PASS: 87 presets, settings persistence, gates, single/multi/text answers, one answer only, deadline, unique IDs and session isolation');
